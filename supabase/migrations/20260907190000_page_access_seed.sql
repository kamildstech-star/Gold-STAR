-- Page-level access, seeded into the permission model that already exists.
--
-- There is NO schema change here, deliberately. A "page" is an ordinary row in
-- public.permissions with its key namespaced `page.<id>`, so:
--   * role defaults are role_permissions rows, same as every capability;
--   * per-person grants and revokes are user_permissions rows, and get expiry,
--     reason and granted_by for free;
--   * has_permission() and effective_permissions() resolve pages with exactly
--     the precedence they already apply to capabilities, so the database and
--     the client cannot disagree about who gets in.
--
-- Because there is no new column or table, src/integrations/supabase/types.ts
-- needs no change and the app runs identically before and after this migration.
-- Until it is applied the client finds no `page.*` rows and falls back to the
-- built-in defaults in src/lib/page-access.ts, which reproduce today's sidebar.
--
-- Re-runnable: the catalogue upserts, the grants are ON CONFLICT DO NOTHING, so
-- running it twice changes nothing and running it after an administrator has
-- edited access does not undo their edits.
--
-- Owner, Admin and Dev are NOT seeded as a special case here; they are allowed
-- in code (src/lib/page-access.ts, rule 2) so that adding a page later cannot
-- lock an administrator out and no row can be un-ticked by accident. The rows
-- below still include them so the management screen shows a consistent picture.
--
-- Page gating is a routing and interface control. Row-level security remains
-- the boundary for the data itself.

