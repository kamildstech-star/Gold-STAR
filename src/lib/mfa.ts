/**
 * Two-factor authentication, on top of `supabase.auth.mfa.*`.
 *
 * TOTP only. Supabase's phone factor needs an SMS provider this project does
 * not have, and an authenticator app is the stronger factor regardless.
 *
 * RECOVERY, PLAINLY: Supabase Auth issues NO backup codes. There is no
 * self-service way back in for someone who loses their phone — the factor has
 * to be deleted for them by an administrator (Admin -> Security in this app,
 * which calls the auth admin API). That is the whole recovery story, and it is
 * why enrolment is opt-in and why the admin page exists.
 */
import { supabase } from "@/integrations/supabase/client";

export type MfaFactor = {
  id: string;
  friendlyName: string | null;
  status: "verified" | "unverified";
  createdAt: string | null;
};

export type MfaEnrolment = {
  factorId: string;
  /** SVG data URL straight from Supabase — no QR library needed. */
  qrCode: string;
  /** The same secret as text, for anyone typing it into a password manager. */
  secret: string;
  uri: string;
};

/**
 * Factors on the current session. Unverified factors are included: an
 * enrolment abandoned halfway leaves one behind, and the settings page has to
 * be able to show it and clear it or the user can never start over.
 */
export async function listMfaFactors(): Promise<MfaFactor[]> {
  const { data, error } = await supabase.auth.mfa.listFactors();
  if (error) throw error;
  return (data?.totp ?? []).map((f) => ({
    id: f.id,
    friendlyName: f.friendly_name ?? null,
    status: f.status as MfaFactor["status"],
    createdAt: f.created_at ?? null,
  }));
}

export function hasVerifiedFactor(factors: MfaFactor[]): boolean {
  return factors.some((f) => f.status === "verified");
}

export async function startMfaEnrolment(friendlyName: string): Promise<MfaEnrolment> {
  const { data, error } = await supabase.auth.mfa.enroll({
    factorType: "totp",
    friendlyName,
  });
  if (error) throw error;
  return {
    factorId: data.id,
    qrCode: data.totp.qr_code,
    secret: data.totp.secret,
    uri: data.totp.uri,
  };
}

/**
 * Finishes enrolment. A factor is only `verified` once a code generated by the
 * app has been checked, so a mistyped secret cannot leave someone holding a
 * factor that will lock them out at the next sign-in.
 */
export async function confirmMfaEnrolment(factorId: string, code: string): Promise<void> {
  const { data: challenge, error: challengeError } = await supabase.auth.mfa.challenge({
    factorId,
  });
  if (challengeError) throw challengeError;
  const { error } = await supabase.auth.mfa.verify({
    factorId,
    challengeId: challenge.id,
    code: code.trim(),
  });
  if (error) throw error;
}

/**
 * Removes a factor. Supabase only downgrades the session from aal2 back to
 * aal1 at the next refresh, so refresh it here — otherwise the user keeps a
 * token claiming a second factor they no longer have.
 */
export async function removeMfaFactor(factorId: string): Promise<void> {
  const { error } = await supabase.auth.mfa.unenroll({ factorId });
  if (error) throw error;
  await supabase.auth.refreshSession();
}

export type MfaGate =
  { required: false } | { required: true; factorId: string; friendlyName: string | null };

/**
 * Does this freshly signed-in session still owe a second factor?
 *
 * `nextLevel` is aal2 only when the user has a verified factor, so this is
 * also the opt-in test: nobody without a factor is ever asked for a code.
 */
export async function mfaGateForSession(): Promise<MfaGate> {
  const { data, error } = await supabase.auth.mfa.getAuthenticatorAssuranceLevel();
  if (error) throw error;
  if (data.nextLevel !== "aal2" || data.nextLevel === data.currentLevel) {
    return { required: false };
  }
  const factors = await listMfaFactors();
  const factor = factors.find((f) => f.status === "verified");
  if (!factor)
    throw new Error(
      "Two-factor authentication is required, but its factor is unavailable. Please sign in again.",
    );
  return { required: true, factorId: factor.id, friendlyName: factor.friendlyName };
}

/** Answers the challenge at sign-in. Throws on a wrong or expired code. */
export async function verifyMfaChallenge(factorId: string, code: string): Promise<void> {
  const { error } = await supabase.auth.mfa.challengeAndVerify({
    factorId,
    code: code.trim(),
  });
  if (error) throw error;
}
